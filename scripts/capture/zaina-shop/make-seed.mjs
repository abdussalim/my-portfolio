// Generates a fictional D1 seed (SQL) + dummy staff credentials for a LOCAL zaina-shop run.
// Usage: node make-seed.mjs <outDir>   -> writes seed.sql and creds.json (creds never committed).
import { writeFileSync, mkdirSync } from "node:fs";
import { randomBytes, pbkdf2Sync, randomUUID } from "node:crypto";
import path from "node:path";

const out = process.argv[2];
if (!out) throw new Error("usage: node make-seed.mjs <outDir>");
mkdirSync(out, { recursive: true });

const username = "staf-demo";
const password = randomBytes(12).toString("base64url");
const salt = randomBytes(16);
const hash = pbkdf2Sync(password, salt, 100000, 32, "sha256").toString("hex");
const passwordHash = `pbkdf2:100000:${salt.toString("hex")}:${hash}`;
const userId = randomUUID();
const q = (s) => (s === null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);
const ts = (d) => d.toISOString().slice(0, 19).replace("T", " ");

const cats = [
  ["10000000-0000-4000-8000-000000000001", "Pecah Belah", "#B96947"],
  ["10000000-0000-4000-8000-000000000002", "Perabot Dapur", "#66704A"],
  ["10000000-0000-4000-8000-000000000003", "Peralatan Rumah", "#50727B"],
  ["10000000-0000-4000-8000-000000000004", "Plastik", "#A87C3D"],
];
// no, cat, sku, name, loc, baseUnit, cost, price, min, finalStock, extraUnit?[name,factor,price]
const prods = [
  [1, 1, "PKM-001", "Piring Keramik Melati (9 Inch)", "Rak A1", "buah", 10000, 15000, 10, 50, ["lusin", 12, 165000]],
  [2, 2, "WAL-024", "Wajan Anti Lengket Teflon (24 cm)", "Rak B2", "buah", 60000, 85000, 5, 15],
  [3, 4, "WMP-003", "Wadah Makanan Plastik Sealware (3 Set)", "Rak C1", "set", 22000, 35000, 8, 24],
  [4, 3, "SLN-001", "Sapu Lantai Nilon Gagang Besi", "Depan", "buah", 18000, 28000, 6, 20],
  [5, 1, "GKD-250", "Gelas Kaca Bening 250 ml", "Rak A2", "buah", 4000, 7000, 24, 96, ["lusin", 12, 78000]],
  [6, 1, "MKP-018", "Mangkuk Porselen Polos 18 cm", "Rak A3", "buah", 9000, 14000, 12, 7, ["lusin", 12, 156000]],
  [7, 2, "PNC-020", "Panci Alumunium 20 cm", "Rak B1", "buah", 45000, 65000, 6, 4],
  [8, 2, "SPT-ST", "Spatula Silikon Tahan Panas", "Rak B3", "buah", 8000, 13000, 10, 30],
  [9, 3, "EMB-012", "Ember Plastik 12 Liter", "Belakang", "buah", 12000, 19000, 8, 3],
  [10, 4, "TPL-S", "Toples Kue Bulat Sedang", "Rak C2", "buah", 7000, 12000, 12, 40, ["set", 4, 44000]],
  [11, 3, "SKT-001", "Sikat Cuci Piring Gagang Panjang", "Depan", "buah", 3000, 6000, 15, 0],
  [12, 4, "BSK-B", "Baskom Plastik Besar", "Rak C3", "buah", 10000, 17000, 8, 18],
];
const pid = (n) => `20000000-0000-4000-8000-${String(n).padStart(12, "0")}`;
const uid = (n, k) => `30000000-0000-4000-800${k}-${String(n).padStart(12, "0")}`;

let sql = `-- fictional demo seed generated by make-seed.mjs\n`;
sql += `INSERT INTO users (id, username, display_name, password_hash) VALUES (${q(userId)}, ${q(username)}, 'Staf Demo', ${q(passwordHash)});\n`;
sql += `INSERT OR REPLACE INTO store_settings (id, store_name, address, phone, timezone, default_minimum_stock) VALUES (1, 'Toko Zaina', 'Jl. Contoh No. 1, Kota Demo', '6281200000000', 'Asia/Jakarta', 5);\n`;
for (const [id, n, c] of cats) sql += `INSERT INTO categories (id, name, color) VALUES (${q(id)}, ${q(n)}, ${q(c)});\n`;

const units = {};
const stock = {}; // running balance
for (const p of prods) {
  const [n, c, sku, name, loc, base, cost, price, min, qty, extra] = p;
  sql += `INSERT INTO products (id, category_id, sku, name, location, base_unit, cost_price, sale_price, minimum_stock) VALUES (${q(pid(n))}, ${q(cats[c - 1][0])}, ${q(sku)}, ${q(name)}, ${q(loc)}, ${q(base)}, ${cost}, ${price}, ${min});\n`;
  units[n] = [{ id: uid(n, 0), name: base, factor: 1, price }];
  sql += `INSERT INTO product_units (id, product_id, name, factor, sale_price, is_default, discount_type, minimum_discount, maximum_discount) VALUES (${q(uid(n, 0))}, ${q(pid(n))}, ${q(base)}, 1, ${price}, 1, 'PERCENTAGE', 0, 10);\n`;
  if (extra) {
    units[n].push({ id: uid(n, 1), name: extra[0], factor: extra[1], price: extra[2] });
    sql += `INSERT INTO product_units (id, product_id, name, factor, sale_price, is_default, discount_type, minimum_discount, maximum_discount) VALUES (${q(uid(n, 1))}, ${q(pid(n))}, ${q(extra[0])}, ${extra[1]}, ${extra[2]}, 0, 'PERCENTAGE', 0, 10);\n`;
  }
  stock[n] = qty;
}

const now = new Date();
let mvSeq = 0;
const mv = (n, unit, type, qIn, qBase, after, at, ref, note) => {
  mvSeq++;
  const cost = type === "RECEIPT" || type === "OPENING" ? prods[n - 1][6] * unit.factor : "NULL";
  sql += `INSERT INTO stock_movements (id, idempotency_key, product_id, unit_id, product_name, unit_name, movement_type, quantity_input, factor_snapshot, quantity_base, balance_after, unit_cost, reference_id, note, created_by, created_at) VALUES (${q(randomUUID())}, ${q("seed-" + mvSeq)}, ${q(pid(n))}, ${q(unit.id)}, ${q(prods[n - 1][3])}, ${q(unit.name)}, ${q(type)}, ${qIn}, ${unit.factor}, ${qBase}, ${after}, ${cost}, ${q(ref)}, ${q(note)}, ${q(userId)}, ${q(at)});\n`;
};

// plan 18 sales over the last 14 days
const sales = [];
for (let i = 0; i < 18; i++) {
  const daysAgo = 13 - Math.floor((i * 14) / 18);
  const when = new Date(now.getTime() - daysAgo * 86400000 - (i % 5) * 3600000 * 2);
  const items = [];
  for (let k = 0; k < 1 + (i % 3); k++) {
    const n = ((i * 3 + k * 5) % 12) + 1;
    if (items.find((x) => x.n === n)) continue;
    const us = units[n];
    const u = us[(i + k) % us.length];
    const qty = u.factor > 1 ? 1 : 1 + ((i + k) % 3);
    const sub = u.price * qty;
    const pct = u.factor > 1 ? 5 : 0;
    const disc = Math.round((sub * pct) / 100);
    items.push({ n, u, qty, sub, pct, disc, tot: sub - disc, base: qty * u.factor });
  }
  sales.push({ when, items });
}
const receipts = [[1, 1, 1], [5, 1, 2]]; // [product, unitIdx, qty]
// opening = final + sold - received, so history ends at the target balance
const open = { ...stock };
for (const s of sales) for (const it of s.items) open[it.n] += it.base;
for (const [n, ui, qy] of receipts) open[n] -= qy * units[n][ui].factor;
const openAt = new Date(now.getTime() - 15 * 86400000);
for (const p of prods) {
  const n = p[0];
  mv(n, units[n][0], "OPENING", open[n], open[n], open[n], ts(openAt), null, "Saldo awal");
  stock[n] = open[n];
}
let saleNo = 0;
for (const s of sales) {
  saleNo++;
  const sid = randomUUID();
  const subtotal = s.items.reduce((a, b) => a + b.sub, 0);
  const discount = s.items.reduce((a, b) => a + b.disc, 0);
  const total = subtotal - discount;
  const paid = Math.ceil(total / 10000) * 10000;
  const num = `INV-${ts(s.when).slice(0, 10).replace(/-/g, "")}-${String(saleNo).padStart(4, "0")}`;
  sql += `INSERT INTO sales (id, sale_number, idempotency_key, sold_at, subtotal, discount, total, amount_paid, change_amount, created_by, created_at) VALUES (${q(sid)}, ${q(num)}, ${q("sale-" + saleNo)}, ${q(ts(s.when))}, ${subtotal}, ${discount}, ${total}, ${paid}, ${paid - total}, ${q(userId)}, ${q(ts(s.when))});\n`;
  for (const it of s.items) {
    sql += `INSERT INTO sale_items (id, sale_id, product_id, unit_id, product_name, unit_name, factor_snapshot, quantity_input, quantity_base, unit_price, cost_price, subtotal, discount_type_snapshot, minimum_discount_snapshot, maximum_discount_snapshot, discount_value, discount_amount, total, created_at) VALUES (${q(randomUUID())}, ${q(sid)}, ${q(pid(it.n))}, ${q(it.u.id)}, ${q(prods[it.n - 1][3])}, ${q(it.u.name)}, ${it.u.factor}, ${it.qty}, ${it.base}, ${it.u.price}, ${prods[it.n - 1][6] * it.u.factor}, ${it.sub}, 'PERCENTAGE', 0, 10, ${it.pct}, ${it.disc}, ${it.tot}, ${q(ts(s.when))});\n`;
    stock[it.n] -= it.base;
    mv(it.n, it.u, "SALE", it.qty, -it.base, stock[it.n], ts(s.when), sid, null);
  }
}
for (const [n, ui, qy] of receipts) {
  const u = units[n][ui];
  stock[n] += qy * u.factor;
  mv(n, u, "RECEIPT", qy, qy * u.factor, stock[n], ts(new Date(now.getTime() - 3600000)), null, "Kiriman supplier (demo)");
}
for (const p of prods) {
  sql += `INSERT INTO inventory_balances (product_id, quantity_base) VALUES (${q(pid(p[0]))}, ${stock[p[0]]});\n`;
}
// monitor: synthetic rows only (agent is NOT running)
sql += `UPDATE monitor_state SET cpu_percent=23, mem_percent=41, gpu_percent=12, last_heartbeat_at=${q(now.toISOString())}, stream_base_url=NULL WHERE id=1;\n`;
const visitors = [18, 31, 27, 22, 35, 29, 24];
for (let d = 0; d < 7; d++) {
  const day = new Date(now.getTime() - d * 86400000).toISOString().slice(0, 10);
  sql += `INSERT OR REPLACE INTO monitor_visitors_daily (date, total_count) VALUES (${q(day)}, ${visitors[d]});\n`;
}
const evs = [["person_enter", "cam2", "Masuk", "Pengunjung masuk (data sintetis)"], ["person_exit", "cam2", "Keluar", "Pengunjung keluar (data sintetis)"]];
for (let i = 0; i < 8; i++) {
  const e = evs[i % 2];
  sql += `INSERT INTO monitor_events (id, event_type, camera_id, label, message, created_at) VALUES (${q(randomUUID())}, ${q(e[0])}, ${q(e[1])}, ${q(e[2])}, ${q(e[3])}, ${q(new Date(now.getTime() - i * 420000).toISOString())});\n`;
}
writeFileSync(path.join(out, "seed.sql"), sql);
writeFileSync(path.join(out, "creds.json"), JSON.stringify({ username, password }));
console.log("seed written", sql.length, "bytes");
